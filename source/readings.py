SMALL = set("ゃゅょぁぃぅぇぉャュョァィゥェォ")


def mora_of(reading: str) -> float:
    if reading == "_":
        return 0.0
    if reading.isdigit():
        return float(reading)
    return float(sum(1 for c in reading if c not in SMALL))
